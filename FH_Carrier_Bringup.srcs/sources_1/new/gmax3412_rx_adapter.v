// FH_Carrier adapter for the Gpixel 16-lane Sub-LVDS training receiver.
//
// Current scope:
//   - 16 data lanes, 2 source-synchronous clocks
//   - 10-bit mode, 16 channels
//   - Table-16 training word 10'h165
//   - 1.20 Gb/s serial rate -> 120 MHz parallel word clock
//   - automatic/retry training after the sensor clocks become active
//   - FH-3 reset-domain cleanup: training/clock module owns all receive-domain resets
//
// The raw 16 x 12-bit words are exposed as image_data (10 LSBs valid in
// 10-bit mode). frame_valid/line_valid remain 0 until the image-sync/BIST
// layer is added in the next integration step.

module gmax3412_rx_adapter
(
    input  wire         rst_n,

    input  wire         clk0_p,
    input  wire         clk0_n,
    input  wire         clk1_p,
    input  wire         clk1_n,

    input  wire [15:0]  data_p,
    input  wire [15:0]  data_n,

    input  wire [3:0]   debug_word_index,
    input  wire         debug_lane_select,
    input  wire         debug_freeze,

    output wire [15:0]  training_result,
    output wire         training_done,

    output wire [9:0]   debug_word,
    output wire         debug_word_valid,
    output wire         debug_clk0_activity,
    output wire         debug_clk1_activity,
    output wire         debug_lane_activity,

    output wire         pixel_clk,
    output wire         frame_valid,
    output wire         line_valid,
    output wire [191:0] image_data
);

    localparam [11:0] GMAX_TRAINING_WORD = 12'h165;
    localparam [1:0]  GMAX_BIT_WIDTH     = 2'b10; // Gpixel encoding: 2 = 10 bit
    localparam [3:0]  GMAX_CHAN_NUM      = 4'd8;  // Gpixel encoding: 8 = 16 channels

    wire        clk_rxg;
    wire        training_done_raw;
    wire [15:0] training_result_raw;
    wire [191:0] data_train;

    // One reset chain per receive domain.  training.v exports the already
    // synchronized 120 MHz reset generated by gmax3412_iob_clock.
    wire rst_rxg_ctrl;

    // V16.3: debug_freeze originates in the AXI GPIO / clk_pl_0 domain and
    // controls the automatic retry FSM in clk_rxg (~120 MHz). Use the AMD XPM
    // primitive rather than a hand-written 2-FF chain so Vivado recognizes this
    // as an intentional asynchronous CDC and applies the XPM timing exception
    // to the source-to-first-stage path. This remains the ONE freeze synchronizer
    // in the design; training.v must not synchronize debug_freeze again.
    wire debug_freeze_rxg;

    xpm_cdc_single #(
        .DEST_SYNC_FF   (2),
        .INIT_SYNC_FF   (0),
        .SIM_ASSERT_CHK (0),
        .SRC_INPUT_REG  (0)
    ) u_xpm_cdc_debug_freeze (
        .dest_out (debug_freeze_rxg),
        .dest_clk (clk_rxg),
        // SRC_INPUT_REG=0 because the AXI GPIO output is already registered.
        .src_clk  (1'b0),
        .src_in   (debug_freeze)
    );

    // Automatic training controller. If STREAM_EN is not active yet, an
    // early attempt may fail; the controller retries until all 16 lanes pass.
    localparam [2:0] ST_WAIT      = 3'd0;
    localparam [2:0] ST_PULSE     = 3'd1;
    localparam [2:0] ST_WAIT_DONE = 3'd2;
    localparam [2:0] ST_RETRY     = 3'd3;
    localparam [2:0] ST_LOCKED    = 3'd4;

    reg [2:0]  train_state = ST_WAIT;
    reg [15:0] wait_count = 16'd0;
    reg        cmd_start_training = 1'b0;

    always @(posedge clk_rxg) begin
        if (rst_rxg_ctrl) begin
            train_state        <= ST_WAIT;
            wait_count         <= 16'd0;
            cmd_start_training <= 1'b0;
        end else begin
            cmd_start_training <= 1'b0;

            case (train_state)
                ST_WAIT: begin
                    if (debug_freeze_rxg) begin
                        // V16 diagnostic hold: do not launch a new attempt while
                        // software is reading the previous completed snapshot.
                        wait_count <= 16'd0;
                    end else if (wait_count == 16'd2047) begin
                        wait_count         <= 16'd0;
                        cmd_start_training <= 1'b1;
                        train_state        <= ST_PULSE;
                    end else begin
                        wait_count <= wait_count + 1'b1;
                    end
                end

                ST_PULSE: begin
                    // One clk_rxg pulse is sufficient; training.v contains
                    // its own synchronizer/edge detector.
                    train_state <= ST_WAIT_DONE;
                end

                ST_WAIT_DONE: begin
                    if (training_done_raw) begin
                        if (training_result_raw == 16'hFFFF) begin
                            train_state <= ST_LOCKED;
                        end else begin
                            wait_count  <= 16'd0;
                            train_state <= ST_RETRY;
                        end
                    end
                end

                ST_RETRY: begin
                    if (debug_freeze_rxg) begin
                        // Finish any in-flight attempt, then remain here until
                        // software releases the diagnostic snapshot hold.
                        wait_count <= 16'd0;
                    end else if (wait_count == 16'd8191) begin
                        wait_count         <= 16'd0;
                        cmd_start_training <= 1'b1;
                        train_state        <= ST_PULSE;
                    end else begin
                        wait_count <= wait_count + 1'b1;
                    end
                end

                ST_LOCKED: begin
                    // Stay locked until external reset/power-cycle.
                    train_state <= ST_LOCKED;
                end

                default: begin
                    train_state <= ST_WAIT;
                    wait_count  <= 16'd0;
                end
            endcase
        end
    end

    wire [15:0] training_result_dbg = training_result_raw;
    wire        training_done_dbg   = training_done_raw;

    training #(
        .DATA_CHAN_NUM (16),
        .CLK_CHAN_NUM  (2),
        .CHN_PORT_WIDTH(4),
        .DATAIN_SWAP   (16'h0000)
    ) u_training (
        .clk_rxg            (clk_rxg),
        .rst_rxg_out        (rst_rxg_ctrl),
        .reset_n            (rst_n),

        .cmos_ddr_clk_p     ({clk1_p, clk0_p}),
        .cmos_ddr_clk_n     ({clk1_n, clk0_n}),
        .cmos_data_p        (data_p),
        .cmos_data_n        (data_n),

        .reg_bit_width      (GMAX_BIT_WIDTH),
        .reg_chan_num       (GMAX_CHAN_NUM),

        .training_word      (GMAX_TRAINING_WORD),
        .cmd_start_training (cmd_start_training),

        .debug_word_index   (debug_word_index),
        .debug_lane_select  (debug_lane_select),
        .debug_freeze       (debug_freeze_rxg),

        .training_done      (training_done_raw),
        .training_result    (training_result_raw),
        .debug_word         (debug_word),
        .debug_word_valid   (debug_word_valid),
        .debug_clk0_activity(debug_clk0_activity),
        .debug_clk1_activity(debug_clk1_activity),
        .debug_lane_activity(debug_lane_activity),

        .dataout            (data_train)
    );

    assign training_result = training_result_dbg;
    assign training_done   = training_done_dbg;
    assign pixel_clk       = clk_rxg;
    assign image_data      = data_train;

    // The next BIST step will decode SOF/SOL/EOL/EOF and drive these.
    assign frame_valid = 1'b0;
    assign line_valid  = 1'b0;

endmodule
